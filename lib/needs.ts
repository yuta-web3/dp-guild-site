// 「何を頼めるか」の入口ページ。トップの4つのカードの遷移先。
//
// 【ここで何をするか】
// サービスの紹介はしない。「これができます」を並べても、読む人は
// それが自分に必要かどうかを判断できない。
//
// 順番は 教育 → 判断 → 分岐 の3段。
//   1. 教育：何が起きるのか。どれくらいで効くのか。貯まるのか消えるのか。
//            続けるのに何が要るのか。
//   2. 判断：読んだ人が「うちは人がいる／いない」「今すぐ／じっくり」を
//            自分で決められる材料を出す。
//   3. 分岐：体制がある → 型を作って渡す（あとは社内で回す）
//            体制がない → 続ける部分をこちらが持つ
//
// 【器は1枚】
// app/needs/[slug]/page.tsx がページの器。ここのデータを足せばページが増える。
// サービスページ（lib/services/）と同じ作りにしている。
//
// 【入口を4つにした根拠】Search Console 実測（2025-09-16〜2026-09-15）
//   1記事あたりの表示回数で比べると、
//     集客 1,619 ／ EC・通販 1,478 ／ 業務改善 798 ／ 制作 725 ／ 採用 210
//   制作は24記事書いて725。しかも上位クエリが「lp hp 違い」など言葉の意味を
//   調べているだけで、発注の手前ですらない。
//   ECは3記事しか無いのに1,478。クエリは「shopify base 比較」「ec 出店」
//   「base shopify 移行」＝これから始める／乗り換える人で、意思決定の直前。
//   → 4つ目は「制作」ではなく「売りたい（EC）」にした。
//   採用は5記事で210と最弱だが、検索以外（紹介・既存客）の流入が
//   ありうるため残している。あいみつの案件カテゴリで要検証。

export type Approach = {
  /** 手段の名前。お客さんが知っている言葉で */
  name: string;
  /** 何が起きるのか。効果の説明 */
  effect: string;
  /** 効き始めるまで */
  speed: string;
  /** 止めたらどうなるか。貯まるのか消えるのか */
  stock: string;
  /** 続けるのに社内で必要なもの */
  needs: string;
};

export type Branch = {
  /** どんな状態の人向けか */
  condition: string;
  /** その人に何を渡すか */
  title: string;
  /** 中身 */
  body: string;
  /** かかる期間 */
  term: string;
  /** 社内で必要な手 */
  hand: string;
  /** 対応するサービスページ。無ければ null */
  service: { slug: string; label: string } | null;
};

export type Need = {
  slug: string;
  /** カードの見出し。トップと揃える */
  title: string;
  /** ページの見出し */
  heading: string;
  /** 見出しの下。誰に向けた話かを1行で */
  lead: string;
  /** よくある状態。読む人が自分を見つけるための入口 */
  symptoms: string[];
  /** 教育の核心。ここだけで判断できる長さにする。FVに入る量しか書かない */
  key: string;
  /** 読みたい人向けの補足。既定では畳んでおく */
  learnTitle: string;
  learnBody: string[];
  /** 手段の比較。効果・速さ・貯まるか・要る体制 */
  approaches: Approach[];
  /** 体制で分ける */
  branchTitle: string;
  branches: Branch[];
  /** メタ */
  metaTitle: string;
  metaDesc: string;
};

