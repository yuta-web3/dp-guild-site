export type Scope = '設計' | '制作' | '計測・分析' | '検索対策' | '集客' | '運用' | '保守' | '開発';

export type Work = {
  id: string;
  /** 分類。トップの絞り込みに使う */
  kind: 'site' | 'ec' | 'sns' | 'system';
  /** 業種 */
  client: string;
  /** 何を作った・やったか（1行） */
  title: string;
  /** FV用。何を作ったかを名詞でそのまま。凝った言い回しにしない */
  short: string;
  /** どこまでやったか */
  scope: Scope[];
  /** 具体的にやったこと */
  did: string[];
  /** 数字。あるものだけ */
  number?: { value: string; label: string };
  /** 掲載許可が取れたら入れる */
  name?: string;
  url?: string;
};

